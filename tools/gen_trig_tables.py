"""Generate sim/math/trig_tables.inc (ARCHITECTURE §4.3). Run: python -I tools/gen_trig_tables.py [--check]

Integer tables for the sim's binary-angle trig, computed with exact decimal arithmetic (no libm), so
the output is byte-identical on every platform. The .inc is committed; tools/tests checks it is current.

  kSinQuarter[i] = round(sin(i/4096 * pi/2) * 2^32), i = 0..4096   (Q32.32 raw, 1.0 = 2^32)
  kAtanUnit[i]   = round(atan(i/4096) / (2 pi) * 65536 * 2^16)     (binary-angle units * 2^16)
"""

from __future__ import annotations

import sys
from decimal import ROUND_HALF_EVEN, Decimal, getcontext
from pathlib import Path

getcontext().prec = 60
N = 4096
OUT = Path(__file__).resolve().parents[1] / "sim" / "math" / "trig_tables.inc"


def pi() -> Decimal:
    # Machin: pi = 16 atan(1/5) - 4 atan(1/239)
    return 16 * atan_series(Decimal(1) / 5) - 4 * atan_series(Decimal(1) / 239)


def atan_series(x: Decimal) -> Decimal:
    """atan for |x| <= ~0.42 by Taylor series."""
    total, term, k, x2 = Decimal(0), x, 0, x * x
    eps = Decimal(10) ** -55
    while abs(term) > eps:
        total += term / (2 * k + 1) if k % 2 == 0 else -term / (2 * k + 1)
        term *= x2
        k += 1
    return total


def atan(x: Decimal) -> Decimal:
    # Reduce: atan(x) = 2 atan(x / (1 + sqrt(1 + x^2))), twice, then the series.
    for _ in range(2):
        x = x / (1 + (1 + x * x).sqrt())
    return 4 * atan_series(x)


def sin(x: Decimal) -> Decimal:
    total, term, k = Decimal(0), x, 1
    eps = Decimal(10) ** -55
    while abs(term) > eps:
        total += term
        term = -term * x * x / ((k + 1) * (k + 2))
        k += 2
    return total


def rnd(d: Decimal) -> int:
    return int(d.quantize(Decimal(1), rounding=ROUND_HALF_EVEN))


def generate() -> str:
    p = pi()
    two32 = Decimal(2) ** 32
    sin_t = [rnd(sin(Decimal(i) / N * p / 2) * two32) for i in range(N + 1)]
    sin_t[N] = 1 << 32  # exact 1.0
    unit = Decimal(65536) / (2 * p) * Decimal(2) ** 16
    atan_t = [rnd(atan(Decimal(i) / N) * unit) for i in range(N + 1)]
    assert atan_t[N] == 8192 << 16  # atan(1) = 1/8 turn exactly

    def table(name: str, ctype: str, vals: list[int]) -> str:
        rows = [", ".join(str(v) for v in vals[i : i + 8]) for i in range(0, len(vals), 8)]
        return f"inline constexpr {ctype} {name}[{len(vals)}] = {{\n    " + ",\n    ".join(rows) + "\n};\n"

    return ("// Generated by tools/gen_trig_tables.py. Do not edit.\n"
            "// kSinQuarter: round(sin(i/4096 * pi/2) * 2^32), i = 0..4096 (Q32.32 raw).\n"
            "// kAtanUnit: round(atan(i/4096) / (2 pi) * 65536 * 2^16) (binary-angle units * 2^16).\n\n"
            + table("kSinQuarter", "std::int64_t", sin_t) + "\n" + table("kAtanUnit", "std::int64_t", atan_t))


def main(argv: list[str]) -> int:
    text = generate()
    if "--check" in argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"{OUT} is out of date: run python -I tools/gen_trig_tables.py", file=sys.stderr)
            return 1
        print("trig tables up to date")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
